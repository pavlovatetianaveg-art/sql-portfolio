-- ============================================
-- БАЗОВАЯ СТРУКТУРА SQL-ЗАПРОСА
-- ============================================
-- Порядок написания строк в запросе ВСЕГДА одинаковый.
-- Это как рецепт — шаги идут строго друг за другом.

SELECT      -- 1. Что выводим (поля, агрегатные функции)
FROM        -- 2. Из какой таблицы, тут же создаём алиас
JOIN        -- 3. Присоединяем другие таблицы (если нужно)
WHERE       -- 4. Фильтруем СЫРЫЕ строки (до группировки)
GROUP BY    -- 5. Группируем строки по признаку
HAVING      -- 6. Фильтруем ПОСЧИТАННЫЕ группы (после группировки)
ORDER BY    -- 7. Сортируем финальный результат


-- ============================================
-- АЛИАСЫ — короткие ярлыки для таблиц
-- ============================================
-- Создаются ОДИН РАЗ в FROM или JOIN, дальше просто используются.

-- FROM users u          -- создали алиас "u" для таблицы users
-- JOIN orders o          -- создали алиас "o" для таблицы orders
--     ON u.user_id = o.user_id   -- используем оба алиаса

-- Правило: алиас = имя переменной. Один раз объявил — дальше
-- просто используешь через точку (u.email, o.order_id).


-- ============================================
-- WHERE vs HAVING — в чём разница
-- ============================================
-- WHERE  -> фильтрует ОДНУ строку, ДО группировки
--           (например: WHERE status = 'completed')
--
-- HAVING -> фильтрует ПОСЧИТАННУЮ ГРУППУ, ПОСЛЕ группировки
--           (например: HAVING SUM(amount) > 1000)
--
-- Сигнальный вопрос: "Я фильтрую одну строку или посчитанную группу?"


-- ============================================
-- ВАЖНОЕ ПРАВИЛО: алиасы в HAVING и ORDER BY
-- ============================================
-- В HAVING алиас использовать НЕЛЬЗЯ — нужно повторить функцию:
--     HAVING SUM(amount) > 1000        -- правильно
--     HAVING total_amount > 1000        -- НЕПРАВИЛЬНО (алиас ещё не существует)
--
-- В ORDER BY алиас использовать МОЖНО — он уже посчитан к этому моменту:
--     ORDER BY total_amount DESC        -- правильно


-- ============================================
-- ПОДЗАПРОСЫ (subqueries)
-- ============================================
-- SQL сначала считает то, что в скобках, потом подставляет
-- результат в основной запрос.

-- WHERE amount > (
--     SELECT AVG(amount) FROM deposits   -- сначала считается ЭТО
-- )
-- Получившееся число подставляется вместо скобок в основной запрос.


-- ============================================
-- GROUP BY vs PARTITION BY (оконные функции)
-- ============================================
-- GROUP BY      -> схлопывает строки в одну на группу
-- PARTITION BY  -> НЕ схлопывает строки, просто считает значение "рядом"
--                  (внутри OVER(...))

-- SUM(amount) OVER (PARTITION BY user_id) AS total_by_user
-- + ORDER BY внутри OVER(...) превращает окно в накопительное (running total)


